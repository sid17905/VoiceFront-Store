"""
provenance_report.py — Generates an HTML report showing exactly where
each component was derived from on the original reference sites.

Output: data/provenance-report.html

The report shows for each component:
  1. The component we built (our HTML + CSS)
  2. The original source element (CSS selector, DOM path, HTML snippet)
  3. Side-by-side visual comparison
  4. Adaptation notes explaining what was changed

Usage:
    python tools/provenance_report.py
"""

from __future__ import annotations

import json
from pathlib import Path

DATA_ROOT = Path(__file__).resolve().parents[1] / "data"
COMPONENT_LIB = DATA_ROOT / "component-library"
OUTPUT_FILE = DATA_ROOT / "provenance-report.html"

SECTION_TYPES = ["nav", "hero", "product_grid", "contact"]

HTML_TEMPLATE = """\
<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<title>VoiceFront Component Provenance Report</title>
<style>
  * {{ box-sizing: border-box; margin: 0; padding: 0; }}
  body {{ font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', sans-serif; background: #f5f5f5; color: #333; padding: 24px; }}
  h1 {{ font-size: 1.8rem; margin-bottom: 8px; }}
  .subtitle {{ color: #666; margin-bottom: 32px; }}
  .category-section {{ margin-bottom: 48px; }}
  .category-title {{ font-size: 1.4rem; margin-bottom: 16px; padding-bottom: 8px; border-bottom: 2px solid #333; }}
  .component-card {{ background: #fff; border: 1px solid #ddd; border-radius: 8px; margin-bottom: 24px; overflow: hidden; }}
  .component-header {{ background: #f0f0f0; padding: 12px 16px; display: flex; justify-content: space-between; align-items: center; }}
  .variant-id {{ font-weight: 700; font-size: 1rem; }}
  .source-badge {{ background: #0066cc; color: #fff; padding: 4px 10px; border-radius: 4px; font-size: 0.8rem; text-decoration: none; }}
  .source-badge:hover {{ background: #0052a3; }}
  .comparison {{ display: grid; grid-template-columns: 1fr 1fr; gap: 0; }}
  .side {{ padding: 16px; }}
  .side-left {{ border-right: 1px solid #eee; background: #fafafa; }}
  .side-label {{ font-size: 0.75rem; text-transform: uppercase; letter-spacing: 1px; color: #999; margin-bottom: 8px; }}
  .code-block {{ background: #1e1e1e; color: #d4d4d4; padding: 12px; border-radius: 4px; font-family: 'Consolas', monospace; font-size: 0.8rem; overflow-x: auto; white-space: pre-wrap; word-break: break-all; max-height: 300px; overflow-y: auto; }}
  .meta-table {{ width: 100%; border-collapse: collapse; margin-top: 12px; }}
  .meta-table td {{ padding: 6px 12px; border-bottom: 1px solid #eee; font-size: 0.85rem; }}
  .meta-table td:first-child {{ font-weight: 600; width: 140px; color: #555; }}
  .adaptation {{ padding: 12px 16px; background: #fffde7; border-top: 1px solid #eee; font-size: 0.9rem; }}
  .adaptation strong {{ color: #666; }}
  .footer {{ text-align: center; padding: 24px; color: #999; font-size: 0.8rem; }}
</style>
</head>
<body>
<h1>VoiceFront Component Provenance Report</h1>
<p class="subtitle">Side-by-side comparison of each component vs its original source reference site.</p>
{content}
<div class="footer">Generated by VoiceFront tools/provenance_report.py</div>
</body>
</html>"""


def load_components() -> dict[str, list[dict]]:
    """Load all component entries grouped by category."""
    components: dict[str, list[dict]] = {}
    for section_type in SECTION_TYPES:
        section_dir = COMPONENT_LIB / section_type
        if not section_dir.exists():
            continue
        for entry_file in sorted(section_dir.glob("*.json")):
            try:
                entry = json.loads(entry_file.read_text(encoding="utf-8"))
            except (json.JSONDecodeError, OSError):
                continue
            if entry.get("review_status") != "APPROVED":
                continue
            cat = entry.get("category", "unknown")
            components.setdefault(cat, []).append(entry)
    return components


def render_component_card(entry: dict) -> str:
    prov = entry.get("provenance", {})
    variant_id = entry.get("variant_id", "unknown")
    section_type = entry.get("section_type", "unknown")

    source_url = prov.get("source_url", entry.get("source_url", "N/A"))
    source_selector = prov.get("source_selector", "N/A")
    source_css_path = prov.get("source_css_path", "N/A")
    source_snippet = prov.get("source_html_snippet", "N/A")
    source_line = prov.get("source_page_line", "N/A")
    source_bb = prov.get("source_bounding_box", {})
    source_tags = prov.get("source_child_tags", [])
    adaptation = prov.get("adaptation_notes", "No adaptation notes provided.")
    source_page = prov.get("source_page_html", "")

    bb_str = ""
    if source_bb:
        bb_str = f"top={source_bb.get('top','?')}px, left={source_bb.get('left','?')}px, {source_bb.get('width','?')}x{source_bb.get('height','?')}px"

    return f"""\
<div class="component-card">
  <div class="component-header">
    <span class="variant-id">{section_type} / {variant_id}</span>
    <a class="source-badge" href="{source_url}" target="_blank" rel="noopener">Visit Source</a>
  </div>
  <div class="comparison">
    <div class="side side-left">
      <div class="side-label">Our Component</div>
      <div class="code-block">{_escape(entry.get('html', ''))}</div>
      <div class="code-block" style="margin-top:8px;color:#a8d8a8;">{_escape(entry.get('css', ''))}</div>
    </div>
    <div class="side">
      <div class="side-label">Original Source Element</div>
      <div class="code-block">{_escape(source_snippet)}</div>
      <table class="meta-table">
        <tr><td>Source URL</td><td><a href="{source_url}" target="_blank">{source_url}</a></td></tr>
        <tr><td>CSS Selector</td><td><code>{source_selector}</code></td></tr>
        <tr><td>DOM Path</td><td><code>{source_css_path}</code></td></tr>
        <tr><td>Bounding Box</td><td>{bb_str or 'N/A'}</td></tr>
        <tr><td>Child Elements</td><td>{', '.join(source_tags) if source_tags else 'N/A'}</td></tr>
        <tr><td>Page HTML Line</td><td>{source_line or 'N/A'}</td></tr>
        <tr><td>Saved HTML</td><td>{source_page or 'N/A'}</td></tr>
      </table>
    </div>
  </div>
  <div class="adaptation"><strong>Adaptation:</strong> {adaptation}</div>
</div>"""


def _escape(text: str) -> str:
    return (
        text.replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
        .replace('"', "&quot;")
    )


def generate_report() -> None:
    components = load_components()
    if not components:
        print("No approved components found in data/component-library/")
        return

    sections = []
    for cat in sorted(components.keys()):
        entries = components[cat]
        cards = "\n".join(render_component_card(e) for e in entries)
        sections.append(
            f'<div class="category-section">\n'
            f'<h2 class="category-title">{cat.title()} ({len(entries)} components)</h2>\n'
            f"{cards}\n"
            f"</div>"
        )

    html = HTML_TEMPLATE.format(content="\n".join(sections))
    OUTPUT_FILE.write_text(html, encoding="utf-8")
    print(f"Provenance report generated: {OUTPUT_FILE}")
    print(f"  {sum(len(v) for v in components.values())} components across {len(components)} categories")


if __name__ == "__main__":
    generate_report()
